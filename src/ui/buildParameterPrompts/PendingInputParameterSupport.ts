import type { JobParameter, JobParameterKind } from "../../jenkins/data/JenkinsDataTypes";

const PARAMETER_KIND_LABELS: Record<JobParameterKind, string> = {
  boolean: "Boolean",
  choice: "Choice",
  credentials: "Credentials",
  file: "File",
  multiChoice: "Multi Choice",
  password: "Password",
  run: "Run",
  string: "String",
  text: "Text"
};

// What the Trigger Build prompts (`promptParameterValue`) can enter for an input step. Kept free
// of `vscode` so the Build Details view model shares the same rules.

/**
 * Whether an input parameter has to be entered on the Jenkins input page: file uploads can't go
 * through inputSubmit, choices with no listed values are generated by Jenkins, a run parameter
 * without its project would be picked from the wrong job (Jenkins accepts any run id), and
 * unrecognized plugin types need their own UI.
 */
export function requiresBrowserForPendingInput(parameter: JobParameter): boolean {
  if (parameter.kind === "file") {
    return true;
  }
  if (parameter.kind === "run") {
    return !parameter.runProjectName?.trim();
  }
  if (parameter.kind === "choice" || parameter.kind === "multiChoice") {
    return !parameter.choices || parameter.choices.length === 0;
  }
  return parameter.isUnrecognizedType === true;
}

export function getBrowserOnlyParameters(parameters: readonly JobParameter[]): JobParameter[] {
  return parameters.filter(requiresBrowserForPendingInput);
}

/** Short label for the parameter's type; unrecognized plugin types show their own type name. */
export function formatPendingInputParameterKind(parameter: JobParameter): string {
  if (parameter.isUnrecognizedType && parameter.rawType) {
    return shortTypeName(parameter.rawType);
  }
  return PARAMETER_KIND_LABELS[parameter.kind] ?? PARAMETER_KIND_LABELS.string;
}

function shortTypeName(rawType: string): string {
  const trimmed = rawType.trim();
  const segments = trimmed.split(/[.$]/).filter((segment) => segment.length > 0);
  return segments[segments.length - 1] ?? trimmed;
}
